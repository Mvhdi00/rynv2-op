#!/usr/bin/env node
// private-server/ -> the RynPrivateServer block inside RynType2.user.js
//
// The server in private-server/ is a Node program (kookywarrior's moomoo.io private
// server). Ryn runs it inside the page instead: every file becomes a CommonJS module
// in one closure, and the Node-only modules it requires are replaced with in-page
// shims (no network, no terminal). Edit the files in private-server/ and rerun this.
//
//   node tools/build-private-server.js [RynType2.user.js]

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "private-server");
const TARGET = path.resolve(process.argv[2] || path.join(ROOT, "RynType2.user.js"));
const BEGIN = "  // ==RynPrivateServer== generated by tools/build-private-server.js from private-server/ - edit there and rebuild";
const END = "  // ==/RynPrivateServer==";
const ANCHOR = "  let _rynOwnSocket = false;\n";

const files = [ "msgpack.js", "index.js", ...fs.readdirSync(path.join(SRC, "src")).filter(f => f.endsWith(".js")).sort().map(f => "src/" + f) ];

const PARAMS = "module, exports, require, process, console, setInterval, clearInterval, setTimeout, clearTimeout";
const modules = files.map(rel => {
  const code = fs.readFileSync(path.join(SRC, rel), "utf8").replace(/\r\n/g, "\n");
  if (code.includes(END.trim()) || code.includes(BEGIN.trim())) throw new Error(rel + " contains the block markers");
  return "    " + JSON.stringify(rel) + ": function (" + PARAMS + ") {\n" + code.replace(/\n$/, "") + "\n    }";
}).join(",\n");

const block = `${BEGIN}
  const RynPrivateServer = (() => {
    const sources = {
${modules}
    };
    const create = (options = {}) => {
      const log = typeof options.log === "function" ? options.log : () => {};
      const quiet = { log: log, info: log, warn: log, error: log, debug: log, clear() {} };
      const intervals = new Set();
      const timers = {
        setInterval: (fn, ms, ...a) => {
          const id = setInterval(() => {
            try {
              fn(...a);
            } catch (e) {
              log("tick error", e);
            }
          }, ms);
          intervals.add(id);
          return id;
        },
        clearInterval: id => {
          intervals.delete(id);
          clearInterval(id);
        },
        setTimeout: (fn, ms, ...a) => setTimeout(fn, ms, ...a),
        clearTimeout: id => clearTimeout(id)
      };
      const env = {
        MODE: options.mode || "SANDBOX",
        PREFIX: options.prefix || "!",
        PASSWORD: "",
        PORT: "0"
      };
      const processShim = { env: env, argv: [] };
      let hub = null;
      class Hub {
        constructor() {
          this.listeners = {};
          this.clients = new Set;
          hub = this;
        }
        on(ev, fn) {
          (this.listeners[ev] || (this.listeners[ev] = [])).push(fn);
          return this;
        }
        addListener(ev, fn) {
          return this.on(ev, fn);
        }
        emit(ev, ...args) {
          for (const fn of this.listeners[ev] || []) fn(...args);
          return true;
        }
        handleUpgrade() {}
      }
      const cache = {};
      const run = rel => {
        if (cache[rel]) return cache[rel].exports;
        const factory = sources[rel];
        if (!factory) throw new Error("private server: no module " + rel);
        const module = { exports: {} };
        cache[rel] = module;
        factory(module, module.exports, require, processShim, quiet, timers.setInterval, timers.clearInterval, timers.setTimeout, timers.clearTimeout);
        return module.exports;
      };
      const codec = (() => {
        const { Encoder, Decoder } = run("msgpack.js");
        const encoder = new Encoder;
        const decoder = new Decoder;
        return {
          encode: value => encoder.encode(value),
          decode: bytes => decoder.decode(bytes)
        };
      })();
      const externals = {
        dotenv: { config() {} },
        ws: { Server: Hub, CONNECTING: 0, OPEN: 1, CLOSING: 2, CLOSED: 3 },
        "msgpack-lite": codec,
        http: {
          createServer: () => ({
            on() {},
            listen(port, cb) {
              if (cb) cb();
            }
          })
        },
        url: { parse: u => new URL(u, "http://localhost") },
        inquirer: { prompt: () => new Promise(() => {}) },
        "node-fetch": async () => ({ json: async () => ({ version: "1.2.2" }) }),
        "./package.json": { version: "1.2.2" }
      };
      function require(name) {
        if (Object.prototype.hasOwnProperty.call(externals, name)) return externals[name];
        let rel = name.replace(/^\\.\\//, "");
        if (!rel.endsWith(".js")) rel += ".js";
        return run(rel);
      }
      run("index.js");
      if (hub === null) throw new Error("private server: index.js never opened its socket server");
      return {
        accept(conn) {
          hub.clients.add(conn);
          conn.on("close", () => hub.clients.delete(conn));
          hub.emit("connection", conn);
        },
        stop() {
          for (const id of intervals) clearInterval(id);
          intervals.clear();
        },
        catalog() {
          const store = run("src/store.js");
          const items = run("src/items.js");
          const pick = list => list.map(x => ({ id: x.id, name: x.name }));
          return {
            hats: pick(store.hats),
            accessories: pick(store.accessories),
            weapons: items.weapons.map(x => ({ id: x.id, name: x.name, type: x.type })),
            items: items.list.map(x => ({ id: x.id, name: x.name, consume: !!x.consume, scale: x.scale })),
            weaponRange: items.weapons.map(x => x.range || 0),
            packets: (() => {
              const codes = run("src/utils.js").PACKETCODE;
              const flip = o => Object.fromEntries(Object.entries(o).map(([name, code]) => [code, name]));
              return { in: flip(codes.RECEIVE), out: flip(codes.SEND) };
            })()
          };
        }
      };
    };
    return { create };
  })();
${END}
`;

let ryn = fs.readFileSync(TARGET, "utf8");
const b = ryn.indexOf(BEGIN), e = ryn.indexOf(END);
if (b !== -1 && e !== -1) {
  ryn = ryn.slice(0, b) + block.replace(/\n$/, "") + ryn.slice(e + END.length);
} else if (b === -1 && e === -1) {
  const at = ryn.indexOf(ANCHOR);
  if (at === -1 || ryn.indexOf(ANCHOR, at + 1) !== -1) throw new Error("anchor not found exactly once: " + JSON.stringify(ANCHOR));
  ryn = ryn.slice(0, at) + block + ryn.slice(at);
} else {
  throw new Error("only one of the RynPrivateServer markers is present");
}
fs.writeFileSync(TARGET, ryn);
console.log("RynPrivateServer: " + files.length + " modules, " + block.length + " bytes -> " + path.relative(ROOT, TARGET));
