#!/usr/bin/env node
/*
 * build-autoheal.js — splice the Auto Heal Engine into the RYN client.
 *
 *   src/RYN_GapFill.user.js              the base client (input, never edited)
 * + src/autoheal/ryn-autoheal-engine.js  the engine (this is the file to edit)
 * = RYN_AutoHeal.user.js                 the build output
 *
 * Every edit is anchored to an exact string in the base client, and an anchor
 * that is missing or ambiguous fails the build. Dropping in a newer RYN
 * surfaces as a build error rather than as a half-merged script.
 *
 * Usage: node tools/build-autoheal.js [--check]
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const BASE = path.join(ROOT, "src", "RYN_GapFill.user.js");
const ENGINE = path.join(ROOT, "src", "autoheal", "ryn-autoheal-engine.js");
const OUT = path.join(ROOT, "RYN_AutoHeal.user.js");

const edits = [];
let source = fs.readFileSync(BASE, "utf8");
const engineSource = fs.readFileSync(ENGINE, "utf8");

function fail(message) {
  console.error("build-autoheal: " + message);
  process.exit(1);
}

/* One anchored replacement. `count` says how many occurrences are expected;
 * anything else is a build failure rather than a silent partial edit. */
function replace(name, anchor, replacement, count) {
  const expected = count === undefined ? 1 : count;
  let seen = 0;
  let index = 0;
  while ((index = source.indexOf(anchor, index)) !== -1) {
    seen += 1;
    index += anchor.length;
  }
  if (seen !== expected) {
    fail(`anchor "${name}" matched ${seen} times, expected ${expected}`);
  }
  source = source.split(anchor).join(replacement);
  edits.push(`${name} (${seen})`);
}

/* Replace a whole region between two anchors, inclusive. */
function replaceRegion(name, startAnchor, endAnchor, replacement) {
  const start = source.indexOf(startAnchor);
  if (start === -1) fail(`region "${name}": start anchor not found`);
  if (source.indexOf(startAnchor, start + 1) !== -1) {
    fail(`region "${name}": start anchor is ambiguous`);
  }
  const endAt = source.indexOf(endAnchor, start);
  if (endAt === -1) fail(`region "${name}": end anchor not found after start`);
  const end = endAt + endAnchor.length;
  source = source.slice(0, start) + replacement + source.slice(end);
  edits.push(`${name} (region ${end - start} chars -> ${replacement.length})`);
}

/* ------------------------------------------------------------------ *
 * 1. The engine itself.
 *
 * The standalone source is a module: a top-level `createRynAutoHealEngine`
 * plus a CommonJS export so tools/test-autoheal.js can require it. Inside the
 * client it is one function in the IIFE, indented to match, and the export
 * footer is dropped.
 * ------------------------------------------------------------------ */
function prepareEngine(text) {
  const exportAt = text.indexOf('\nif (typeof module !== "undefined"');
  const body = exportAt === -1 ? text : text.slice(0, exportAt);
  return body
    .split("\n")
    .map(line => (line.length ? "  " + line : line))
    .join("\n")
    .replace(/\s+$/, "");
}

const BANNER = [
  "  /* ==================================================================== *",
  "   * RYN Auto Heal Engine — generated by tools/build-autoheal.js from",
  "   * src/autoheal/ryn-autoheal-engine.js. Edit that file, not this block.",
  "   * Design notes: docs/AUTOHEAL_ENGINE.md",
  "   * ==================================================================== */"
].join("\n");

/* The dependency object. The engine reads every table lazily through getters,
 * because the client declares `Settings_default` after the point the engine is
 * spliced in.
 *
 * Weapons, Projectiles and Config are new here, and their absence was a real
 * defect rather than a missing nicety: without them the ranged detectors
 * priced every held musket and bow at zero damage, so a report was produced
 * and then ranked below everything on the board. */
const DEPS = [
  "  const AutoHealEngine_default = createRynAutoHealEngine({",
  "    get Items() { return Items; },",
  "    get Hats() { return Hats; },",
  "    get Accessories() { return Accessories; },",
  "    get Weapons() { return Weapons; },",
  "    get Projectiles() { return Projectiles; },",
  "    get Config() { return Config_default; },",
  "    get Settings() { return Settings_default; }",
  "  });"
].join("\n");

replaceRegion(
  "auto-heal-engine",
  "  /* ==================================================================== *\n   * RYN Auto Heal Engine",
  "  const AutoHealEngine_default = createRynAutoHealEngine({\n" +
    "    get Items() { return Items; },\n" +
    "    get Hats() { return Hats; },\n" +
    "    get Accessories() { return Accessories; },\n" +
    "    get Settings() { return Settings_default; }\n" +
    "  });",
  BANNER + "\n" + prepareEngine(engineSource) + "\n\n" + DEPS
);

/* ------------------------------------------------------------------ *
 * 2. The gear lock.
 *
 * Requirement 23 asks for ONE final hat decision. `forceHat` alone cannot be
 * it: modules later in the loop assign it directly (`ModuleHandler.forceHat =
 * 7`), so the last writer wins rather than the highest priority, and the heal
 * engine runs early. The lock is read ahead of forceHat by the one module that
 * actually equips, and it carries the tick it was made on, so it can never
 * outlive the threat that produced it or survive into a tick the engine did
 * not speak on.
 *
 * With the engine off, or with no threat asking for gear, no lock is ever set
 * and both functions behave exactly as they did.
 * ------------------------------------------------------------------ */
const HAT_LOCK_HELPER = [
  "    // The Auto Heal Engine's defensive gear decision, and the reason it is",
  "    // read here rather than through forceHat: modules that run after the",
  "    // engine assign forceHat directly, so on forceHat alone the last writer",
  "    // in the module list would win a question that is supposed to be decided",
  "    // once, by threat priority. The lock is only ever set for the tick it was",
  "    // taken on, and only while a real threat is asking for gear.",
  "    _ahGearHat(ModuleHandler) {",
  "      const lock = ModuleHandler._ahGearLock;",
  "      if (!lock) return null;",
  "      if (lock.tick !== ModuleHandler.tickCount) return null;",
  "      return lock.hat;",
  "    }"
].join("\n");

replace(
  "autohat-handle-equip",
  [
    "    handleEquip(type, use) {",
    "      const {_ModuleHandler: ModuleHandler} = this.client;",
    "      if (type === 0 && ModuleHandler.forceHat !== null) {",
    "        use = ModuleHandler.forceHat;",
    "      }"
  ].join("\n"),
  [
    HAT_LOCK_HELPER,
    "    handleEquip(type, use) {",
    "      const {_ModuleHandler: ModuleHandler} = this.client;",
    "      if (type === 0) {",
    "        const locked = this._ahGearHat(ModuleHandler);",
    "        if (locked !== null) {",
    "          use = locked;",
    "        } else if (ModuleHandler.forceHat !== null) {",
    "          use = ModuleHandler.forceHat;",
    "        }",
    "      }"
  ].join("\n")
);

replace(
  "autohat-next-hat",
  [
    "    getNextHat() {",
    "      const {_ModuleHandler: ModuleHandler, myPlayer: myPlayer} = this.client;",
    "      if (ModuleHandler.forceHat !== null) {",
    "        return ModuleHandler.forceHat;",
    "      }"
  ].join("\n"),
  [
    "    getNextHat() {",
    "      const {_ModuleHandler: ModuleHandler, myPlayer: myPlayer} = this.client;",
    "      const locked = this._ahGearHat(ModuleHandler);",
    "      if (locked !== null) {",
    "        return locked;",
    "      }",
    "      if (ModuleHandler.forceHat !== null) {",
    "        return ModuleHandler.forceHat;",
    "      }"
  ].join("\n")
);

/* The lock is per-tick state and is cleared where every other per-tick field
 * is cleared, so a tick the engine does not speak on carries no gear claim. */
replace(
  "modulehandler-tick-reset",
  [
    "      this.useHat = null;",
    "      this.forceHat = null;",
    "      this.shouldEquipSoldier = false;"
  ].join("\n"),
  [
    "      this.useHat = null;",
    "      this.forceHat = null;",
    "      // The Auto Heal Engine's gear lock is per-tick, like forceHat. It is",
    "      // re-asserted by the engine on every tick it still wants the hat, so",
    "      // clearing it here is what makes releasing gear free and automatic.",
    "      this._ahGearLock = null;",
    "      this.shouldEquipSoldier = false;"
  ].join("\n")
);

/* ------------------------------------------------------------------ *
 * 3. Settings: the two new sub-options, and the menu entries for them.
 * ------------------------------------------------------------------ */
replace(
  "settings-defaults",
  [
    "    _autoHealWash: true,",
    "    _autoHealStrict: true,",
    "    _autoHealReserve: 15,"
  ].join("\n"),
  [
    "    _autoHealWash: true,",
    "    _autoHealStrict: true,",
    "    // Defensive gear and projectile micro-evasion. Both belong to the Auto",
    "    // Heal Engine and do nothing while it is off.",
    "    _autoHealGear: true,",
    "    _autoHealEvade: true,",
    "    _autoHealReserve: 15,"
  ].join("\n")
);

const MENU_ANCHOR =
  '            <div class=\\"content-option\\">\\r\\n' +
  '                <span class=\\"option-title\\">Heal Reserve</span>';

const MENU_ADDITION =
  '            <div class=\\"content-option\\">\\r\\n' +
  '                <label class=\\"option-title\\" for=\\"_autoHealGear\\">Defensive Gear</label>\\r\\n' +
  '                <label class=\\"switch-checkbox\\">\\r\\n' +
  '                    <input id=\\"_autoHealGear\\" type=\\"checkbox\\"></input>\\r\\n' +
  '                    <span></span>\\r\\n' +
  '                </label>\\r\\n' +
  '                <span class=\\"option-description\\">One hat decision for the whole defence. ' +
  'Soldier against melee, insta and spike sequences; Emp against a turret stack. ' +
  'Equipped early enough to land before the hit and dropped again when the threat is over.</span>\\r\\n' +
  '            </div>\\r\\n' +
  '            <div class=\\"content-option\\">\\r\\n' +
  '                <label class=\\"option-title\\" for=\\"_autoHealEvade\\">Projectile Evasion</label>\\r\\n' +
  '                <label class=\\"switch-checkbox\\">\\r\\n' +
  '                    <input id=\\"_autoHealEvade\\" type=\\"checkbox\\"></input>\\r\\n' +
  '                    <span></span>\\r\\n' +
  '                </label>\\r\\n' +
  '                <span class=\\"option-description\\">Steps the smallest distance out of an incoming ' +
  'arrow or musket ball when there is time to and the destination is safe. Never into a spike, ' +
  'a trap, another shot or melee reach.</span>\\r\\n' +
  '            </div>\\r\\n' +
  MENU_ANCHOR;

replace("menu-autoheal-suboptions", MENU_ANCHOR, MENU_ADDITION);

/* ------------------------------------------------------------------ *
 * 4. Header — say what this build is.
 * ------------------------------------------------------------------ */
replace(
  "userscript-header",
  "// @name           ! RYN Client v5 + Auto Heal Engine",
  "// @name           ! RYN Client v5 + Auto Heal Engine v2"
);

/* ------------------------------------------------------------------ *
 * Checks that must hold in the output.
 * ------------------------------------------------------------------ */
const invariants = [
  ["engine present", /function createRynAutoHealEngine\(deps\)/],
  ["shame target is 0", /SHAME_TARGET:\s*0/],
  ["weapons injected", /get Weapons\(\) \{ return Weapons; \}/],
  ["projectiles injected", /get Projectiles\(\) \{ return Projectiles; \}/],
  ["config injected", /get Config\(\) \{ return Config_default; \}/],
  ["gear lock read", /_ahGearHat\(ModuleHandler\)/],
  ["gear lock cleared", /this\._ahGearLock = null;/],
  ["anti-insta ownership guard", /if \(Settings_default\._autoHealEngine\) \{\n\s+return;/],
  ["no module export in the bundle", /^(?!.*module\.exports = \{ createRynAutoHealEngine \})/s]
];
for (const [name, pattern] of invariants) {
  if (!pattern.test(source)) fail(`invariant failed: ${name}`);
}
/* Exactly one engine, exactly one deps construction. */
const engines = (source.match(/function createRynAutoHealEngine\(deps\)/g) || []).length;
if (engines !== 1) fail(`expected 1 engine definition, found ${engines}`);
const constructions = (source.match(/createRynAutoHealEngine\(\{/g) || []).length;
if (constructions !== 1) fail(`expected 1 engine construction, found ${constructions}`);

if (process.argv.indexOf("--check") !== -1) {
  console.log("build-autoheal: anchors OK\n  " + edits.join("\n  "));
  process.exit(0);
}

fs.writeFileSync(OUT, source);
console.log("build-autoheal: wrote " + path.relative(ROOT, OUT) +
  " (" + source.length + " bytes)");
console.log("  " + edits.join("\n  "));
