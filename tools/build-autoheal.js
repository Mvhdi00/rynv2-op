#!/usr/bin/env node
/*
 * build-autoheal.js
 *
 * Builds RYN_AutoHeal.user.js: the RYN v5.4 client with the new Auto Heal
 * Engine spliced in as one more module in ModuleHandler's list.
 *
 * The engine itself lives in src/autoheal/ryn-autoheal-engine.js and is
 * injected verbatim, so it can be read, linted and simulated on its own
 * (node tools/sim-autoheal.js). What this file adds around it is the wiring:
 * the module registration, the settings keys, the menu entries, and the two
 * one-line ownership guards that stop the shipped heal paths from pressing
 * alongside the engine.
 *
 * Nothing else in the client is touched. Every edit goes through edit(), which
 * fails the build if an anchor is missing or ambiguous, so a client update can
 * never produce a half-wired script.
 *
 *   node tools/build-autoheal.js
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const BASE = path.join(ROOT, "src/RYN_Client_v5.4.user.js");
const ENGINE = path.join(ROOT, "src/autoheal/ryn-autoheal-engine.js");
const OUT = path.join(ROOT, "RYN_AutoHeal.user.js");

let code = fs.readFileSync(BASE, "utf8");
const engineSource = fs.readFileSync(ENGINE, "utf8");
const applied = [];

function edit(label, find, replace) {
  const parts = code.split(find);
  if (parts.length === 1) throw new Error(`anchor not found: ${label}`);
  if (parts.length > 2) throw new Error(`anchor is ambiguous (${parts.length - 1} hits): ${label}`);
  code = parts[0] + replace + parts[1];
  applied.push(label);
}

/* ------------------------------------------------------------------ *
 * 1. Userscript header
 *
 * A distinct @name so this installs beside the stock client rather than
 * replacing it — Tampermonkey keys scripts by name.
 * ------------------------------------------------------------------ */
edit(
  "header: name",
  "// @name           ! RYN Client v5 ",
  "// @name           ! RYN Client v5 + Auto Heal Engine"
);
edit(
  "header: description",
  "// @description     ! have fun — v5.4 ports autoheal, automill, anti smart tick, safe soldier and the packet budget from Novastorm",
  "// @description     ! have fun — v5.4 plus a new Auto Heal Engine: shame control, predictive defense and threat priority, built from the game bundle"
);

/* ------------------------------------------------------------------ *
 * 2. The engine
 *
 * Spliced in ahead of ModuleHandler, which is the first thing that needs the
 * class. Its dependencies are handed over as getters: Items, Hats and
 * Accessories are already declared by this point, but Settings_default is not
 * — it is declared with the rest of the menu wiring, thousands of lines later —
 * and a getter defers the read to the first tick, long after everything is
 * initialised.
 * ------------------------------------------------------------------ */
const engineBlock = `
  /* ==================================================================== *
   * RYN Auto Heal Engine — generated by tools/build-autoheal.js from
   * src/autoheal/ryn-autoheal-engine.js. Edit that file, not this block.
   * Design notes: docs/AUTOHEAL_ENGINE.md
   * ==================================================================== */
${engineSource
  .replace(/^\s*\/\* eslint-disable no-unused-vars \*\/\s*$/m, "")
  .replace(/if \(typeof module !== "undefined" && module\.exports\) \{[\s\S]*?\n\}\n?$/, "")
  .replace(/^/gm, "  ")
  .replace(/\s+$/, "")}

  const AutoHealEngine_default = createRynAutoHealEngine({
    get Items() { return Items; },
    get Hats() { return Hats; },
    get Accessories() { return Accessories; },
    get Settings() { return Settings_default; }
  });

`;

edit("engine: source spliced in before ModuleHandler", "  class ModuleHandler {", engineBlock + "  class ModuleHandler {");

/* ------------------------------------------------------------------ *
 * 3. Module registration
 *
 * Ahead of antiInsta in both the map and the run order, so the engine has the
 * tick before the shipped heal rule would have taken it.
 * ------------------------------------------------------------------ */
edit(
  "module: staticModules entry",
  "        antiInsta: new AntiInsta_default(client2),",
  "        autoHealEngine: new AutoHealEngine_default(client2),\n" +
  "        antiInsta: new AntiInsta_default(client2),"
);
edit(
  "module: run order",
  "this.staticModules.antiInsta, this.staticModules.shameReset,",
  "this.staticModules.autoHealEngine, this.staticModules.antiInsta, this.staticModules.shameReset,"
);

/* ------------------------------------------------------------------ *
 * 4. Ownership handoff
 *
 * Two guards, both conditional on the engine's own toggle, so turning it off
 * hands healing straight back to the shipped code.
 *
 * AntiInsta keeps its Anti Smart Tick branch — that is a refusal to break out
 * of a trap, not a heal rule, and it has its own toggle. Only the novastorm
 * heal rule below it stands down.
 * ------------------------------------------------------------------ */
edit(
  "handoff: AntiInsta heal rule stands down",
  "      let totalDmgPot = EnemyManager2.potentialDamage + EnemyManager2.potentialSpikeDamage;",
  "      // Ownership: while the Auto Heal Engine is on it drives every food\n" +
  "      // press, and two rules pressing on the same tick is double food and\n" +
  "      // double shame. Anti Smart Tick above keeps its branch either way.\n" +
  "      if (Settings_default._autoHealEngine) {\n" +
  "        return;\n" +
  "      }\n" +
  "      let totalDmgPot = EnemyManager2.potentialDamage + EnemyManager2.potentialSpikeDamage;"
);
edit(
  "handoff: ShameReset stands down",
  "      if (Settings_default._autoheal && !this.notSave() && (this.shouldReset || this.tickToggle)) {",
  "      // Ownership: the engine's wash path covers this, and both of them\n" +
  "      // asking for the bull hat on the same tick is a fight over forceHat.\n" +
  "      if (Settings_default._autoHealEngine) {\n" +
  "        return;\n" +
  "      }\n" +
  "      if (Settings_default._autoheal && !this.notSave() && (this.shouldReset || this.tickToggle)) {"
);

/* ------------------------------------------------------------------ *
 * 5. Settings
 *
 * On by default. The shipped rule it replaces cannot fire at all — it gates on
 * `tempHealth < maxHealth` and Player.maxHealth is `Math.LN1`, i.e. undefined —
 * so defaulting the engine off would ship a client that does not heal.
 * ------------------------------------------------------------------ */
edit(
  "settings: engine keys",
  "    _autoheal: true,",
  "    _autoheal: true,\n" +
  "    _autoHealEngine: true,\n" +
  "    _autoHealWash: true,\n" +
  "    _autoHealStrict: true,\n" +
  "    _autoHealReserve: 15,"
);

/* ------------------------------------------------------------------ *
 * 6. Menu
 *
 * The page constants are JS string literals: decode, splice, re-encode.
 * Checkboxes and sliders bind themselves by id off the settings object
 * (UI.getElements queries `input[type='checkbox'][id]` and `[type='range'][id]`).
 * ------------------------------------------------------------------ */
function patchPage(constName, anchorHtml, insertHtml) {
  const declaration = `const ${constName} = `;
  const start = code.indexOf(declaration);
  if (start === -1) throw new Error(`page constant not found: ${constName}`);
  const lineEnd = code.indexOf("\n", start);
  const literal = code.slice(start + declaration.length, lineEnd).replace(/;\s*$/, "");
  // eslint-disable-next-line no-eval
  const html = eval(literal);
  if (!html.includes(anchorHtml)) throw new Error(`page anchor not found in ${constName}`);
  const patched = html.replace(anchorHtml, insertHtml + anchorHtml);
  code =
    code.slice(0, start + declaration.length) +
    JSON.stringify(patched) +
    ";" +
    code.slice(lineEnd);
  applied.push(`menu: options added to ${constName}`);
}

const option = (id, label) =>
  `            <div class="content-option">\r
                <label class="option-title" for="${id}">${label}</label>\r
                <label class="switch-checkbox">\r
                    <input id="${id}" type="checkbox"></input>\r
                    <span></span>\r
                </label>\r
            </div>\r
`;

patchPage(
  "Combat_default",
  `            <div class="content-option">\r
                <label class="option-title" for="_autoShield">Auto Shield</label>`,
  option("_autoHealEngine", "Auto Heal Engine") +
  `            <div class="sub-options">\r
` +
  option("_autoHealWash", "Shame Wash") +
  option("_autoHealStrict", "Strict Shame Guard") +
  `            <div class="content-option">\r
                <span class="option-title">Heal Reserve</span>\r
                <label class="slider">\r
                    <span class="slider-value"></span>\r
                    <input id="_autoHealReserve" type="range" step="5" min="0" max="40">\r
                </label>\r
            </div>\r
            </div>\r
`
);

/* ------------------------------------------------------------------ *
 * 7. Write
 * ------------------------------------------------------------------ */
fs.writeFileSync(OUT, code);

console.log(`built ${path.relative(ROOT, OUT)}  (${(code.length / 1024).toFixed(0)} KB)`);
for (const label of applied) console.log(`  - ${label}`);
